import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * `npm run notices` — the third-party notices for what the artifacts actually ship (review 2026-11-05 L4).
 *
 * The hand-written table at the top of `THIRD_PARTY_NOTICES.md` names the direct dependencies and where
 * each ships. The host bundles are built with `noExternal: true` and the extension bundle pulls in the
 * unified/micromark family, so what ships is the whole production closure of those dependencies - which
 * the hand-written table cannot keep up with and the zip did not carry at all. This script walks the
 * lockfile from the two shipped workspaces (`apps/extension`, `packages/agent-host`) through
 * `dependencies` only - never dev, never peer, and never optional, except koffi's win32-x64 binary
 * package, which `scripts/package.ts` stages by name - and writes, between two markers in the notices
 * file, one row per package (name, version, licence as its own `package.json` declares it) followed by
 * the licence text each package carries. The contract test regenerates and compares, so the committed
 * file cannot drift from the lockfile.
 *
 * This file imports nothing from the repository itself: it runs under `--experimental-strip-types`.
 */

export const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const NOTICES_FILE = "THIRD_PARTY_NOTICES.md";
export const GENERATED_START = "<!-- generated by scripts/third-party-notices.ts: start -->";
export const GENERATED_END = "<!-- generated by scripts/third-party-notices.ts: end -->";

/** The workspaces whose production dependencies ship, and the optional packages staged by name. */
export const SHIPPED_WORKSPACES = ["apps/extension", "packages/agent-host"] as const;
export const SHIPPED_OPTIONAL_PACKAGES = ["@koromix/koffi-win32-x64"] as const;

type LockPackage = {
  version?: string;
  dependencies?: Record<string, string>;
  optionalDependencies?: Record<string, string>;
  dev?: boolean;
  optional?: boolean;
  link?: boolean;
  resolved?: string;
  license?: string;
};

type Lockfile = { lockfileVersion: number; packages: Record<string, LockPackage> };

export type ShippedPackage = {
  name: string;
  version: string;
  /** The lockfile path, e.g. `node_modules/zod` or `node_modules/a/node_modules/b`. */
  path: string;
};

/**
 * Node's resolution against the lockfile's layout: from a dependant at `fromPath`, `name` is the
 * nearest `node_modules/<name>` walking up through the nested `node_modules` directories to the root.
 */
function resolveDependency(packages: Record<string, LockPackage>, fromPath: string, name: string): string | undefined {
  let base = fromPath;
  for (;;) {
    const candidate = base === "" ? `node_modules/${name}` : `${base}/node_modules/${name}`;
    if (candidate in packages) return candidate;
    const at = base.lastIndexOf("/node_modules/");
    if (at === -1) {
      // A workspace path (`apps/extension`) resolves against the root like everything else.
      if (base !== "") {
        base = "";
        continue;
      }
      return undefined;
    }
    base = base.slice(0, at);
  }
}

/** The production closure of the shipped workspaces, by lockfile path, sorted by name then path. */
export function shippedPackages(lock: Lockfile): ShippedPackage[] {
  if (lock.lockfileVersion < 3) throw new Error(`package-lock.json is lockfileVersion ${lock.lockfileVersion}; this reads v3`);
  const { packages } = lock;
  const seen = new Set<string>();
  const queue: string[] = [];
  const enqueue = (fromPath: string, names: Iterable<string>): void => {
    for (const name of names) {
      const path = resolveDependency(packages, fromPath, name);
      if (path === undefined) throw new Error(`${fromPath || "root"} depends on ${name}, which the lockfile does not place`);
      if (seen.has(path)) continue;
      seen.add(path);
      queue.push(path);
    }
  };
  for (const workspace of SHIPPED_WORKSPACES) {
    const entry = packages[workspace];
    if (entry === undefined) throw new Error(`the lockfile has no entry for the workspace ${workspace}`);
    enqueue(workspace, Object.keys(entry.dependencies ?? {}));
  }
  for (const name of SHIPPED_OPTIONAL_PACKAGES) enqueue("", [name]);
  const out: ShippedPackage[] = [];
  while (queue.length > 0) {
    const path = queue.shift()!;
    const entry = packages[path]!;
    // A workspace link (`node_modules/@hallpass/contracts` -> `packages/contracts`) is this repository's
    // own code; its dependencies still ship, so they are followed from the linked path.
    if (entry.link === true) {
      const target = entry.resolved ?? "";
      const linked = packages[target];
      if (linked !== undefined) enqueue(target, Object.keys(linked.dependencies ?? {}));
      continue;
    }
    if (entry.dev === true) continue;
    const name = path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
    out.push({ name, version: entry.version ?? "?", path });
    enqueue(path, Object.keys(entry.dependencies ?? {}));
  }
  return out.sort((a, b) => (a.name === b.name ? a.path.localeCompare(b.path) : a.name.localeCompare(b.name)));
}

export type NoticeEntry = ShippedPackage & { license: string; text: string | undefined };

const LICENSE_FILE = /^(licen[cs]e|copying)(\.|$)/iu;

/**
 * The licence a package declares for itself and the text it carries, read from its install directory.
 * A package that is not installed on this platform (koffi's binary packages are optional and per
 * platform) is read as its parent's: the same author publishes them under the same licence, and the
 * text is the parent's, which is what makes the generated file the same on every platform.
 */
export function readNotice(pkg: ShippedPackage, root: string = repoRoot): NoticeEntry {
  let dir = resolve(root, pkg.path);
  if (!existsSync(dir) && pkg.name.startsWith("@koromix/koffi-")) dir = resolve(root, "node_modules/koffi");
  const manifestPath = resolve(dir, "package.json");
  if (!existsSync(manifestPath)) throw new Error(`${pkg.name} is not installed at ${pkg.path}; run npm ci`);
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as { license?: unknown; licenses?: Array<{ type?: string }> };
  const license =
    typeof manifest.license === "string"
      ? manifest.license
      : typeof manifest.license === "object" && manifest.license !== null && typeof (manifest.license as { type?: unknown }).type === "string"
        ? (manifest.license as { type: string }).type
        : Array.isArray(manifest.licenses)
          ? manifest.licenses.map((entry) => entry.type ?? "?").join(" OR ")
          : "UNKNOWN";
  const file = readdirSync(dir).find((entry) => LICENSE_FILE.test(entry));
  const text = file === undefined ? undefined : readFileSync(resolve(dir, file), "utf8").replace(/\r\n/g, "\n").trim();
  return { ...pkg, license, text };
}

/** The generated section, markers included. */
export function renderGenerated(entries: NoticeEntry[]): string {
  const lines: string[] = [GENERATED_START, "", `### Every package the artifacts ship (${entries.length})`, ""];
  lines.push(
    "Walked from the lockfile through the production dependencies of `apps/extension` and `packages/agent-host`",
    "(plus koffi's win32-x64 binary package, which the zip stages by name): what the bundles can contain. The",
    "licence is the one each package declares in its own `package.json`; the text that follows is the licence",
    "file it carries. Regenerate with `npm run notices`; the contract test fails when this section is stale.",
    "",
    "| Package | Version | Licence |",
    "| --- | --- | --- |",
  );
  for (const entry of entries) lines.push(`| ${entry.name} | ${entry.version} | ${entry.license} |`);
  lines.push("", "### Licence texts", "");
  for (const entry of entries) {
    lines.push(`#### ${entry.name} ${entry.version} (${entry.license})`, "");
    if (entry.text === undefined) {
      lines.push(`_The package carries no licence file; its \`package.json\` declares ${entry.license}._`, "");
    } else {
      lines.push("```text", ...entry.text.split("\n"), "```", "");
    }
  }
  lines.push(GENERATED_END);
  return lines.join("\n");
}

export function generatedSection(root: string = repoRoot): string {
  const lock = JSON.parse(readFileSync(resolve(root, "package-lock.json"), "utf8")) as Lockfile;
  return renderGenerated(shippedPackages(lock).map((pkg) => readNotice(pkg, root)));
}

/** The notices file with its generated section replaced (or appended, the first time). */
export function withGenerated(current: string, generated: string): string {
  const start = current.indexOf(GENERATED_START);
  const end = current.indexOf(GENERATED_END);
  if (start === -1 || end === -1 || end < start) return `${current.trimEnd()}\n\n${generated}\n`;
  return `${current.slice(0, start)}${generated}${current.slice(end + GENERATED_END.length)}`;
}

const invokedDirectly = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const file = resolve(repoRoot, NOTICES_FILE);
  const current = existsSync(file) ? readFileSync(file, "utf8") : "";
  const next = withGenerated(current, generatedSection());
  if (process.argv.includes("--check")) {
    if (next !== current) {
      process.stderr.write(`${NOTICES_FILE} is stale; run npm run notices\n`);
      process.exitCode = 1;
    }
  } else {
    writeFileSync(file, next, "utf8");
    process.stdout.write(`${NOTICES_FILE} written\n`);
  }
}
